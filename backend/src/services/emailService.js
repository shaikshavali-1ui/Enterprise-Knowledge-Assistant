import nodemailer from 'nodemailer';
import { config } from '../config/index.js';

class EmailService {
  constructor() {
    this.emailLogs = [];
    this.transporter = null;
    this.initTransporter();
  }

  /**
   * Initialize Nodemailer SMTP Transporter
   */
  async initTransporter() {
    try {
      if (config.smtp.user && config.smtp.pass) {
        this.transporter = nodemailer.createTransport({
          host: config.smtp.host,
          port: config.smtp.port,
          secure: config.smtp.secure,
          auth: {
            user: config.smtp.user,
            pass: config.smtp.pass
          },
          tls: {
            rejectUnauthorized: false
          }
        });
        console.log('[EmailService] SMTP Transporter initialized with user credentials.');
      } else {
        // Fallback test transport using Ethereal sandbox
        const testAccount = await nodemailer.createTestAccount();
        this.transporter = nodemailer.createTransport({
          host: 'smtp.ethereal.email',
          port: 587,
          secure: false,
          auth: {
            user: testAccount.user,
            pass: testAccount.pass
          },
          tls: {
            rejectUnauthorized: false
          }
        });
        console.log(`[EmailService] SMTP Test Account created (${testAccount.user}). Ready for dispatch.`);
      }
    } catch (err) {
      console.warn('[EmailService] SMTP Transporter initialization fallback to internal simulator:', err.message);
      this.transporter = null;
    }
  }

  /**
   * Generate HTML email template from parameters
   */
  generateEmailTemplate({ type, recipient, subject, body, variables }) {
    const primaryColor = '#4f46e5';

    let htmlBody = `
      <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; border: 1px solid #e5e7eb; border-radius: 8px; overflow: hidden; background-color: #ffffff;">
        <div style="background-color: ${primaryColor}; padding: 20px; text-align: center;">
          <h2 style="color: #ffffff; margin: 0; font-size: 20px;">Enterprise Knowledge Assistant</h2>
          <p style="color: #c7d2fe; margin: 4px 0 0 0; font-size: 13px;">Automated Enterprise Communication System</p>
        </div>
        <div style="padding: 24px; color: #374151; font-size: 15px; line-height: 1.6;">
          <h3 style="color: #111827; margin-top: 0;">${subject}</h3>
          <div>${body ? body.replace(/\n/g, '<br/>') : 'No additional details provided.'}</div>

          ${variables ? `
            <div style="margin-top: 20px; padding: 16px; background-color: #f3f4f6; border-radius: 6px; border-left: 4px solid ${primaryColor};">
              <h4 style="margin: 0 0 8px 0; color: #1f2937; font-size: 14px;">Summary Details</h4>
              <table style="width: 100%; border-collapse: collapse; font-size: 13px;">
                ${Object.entries(variables).map(([k, v]) => `
                  <tr>
                    <td style="padding: 4px 0; font-weight: bold; color: #4b5563; text-transform: capitalize;">${k.replace(/([A-Z])/g, ' $1')}:</td>
                    <td style="padding: 4px 0; color: #111827;">${v}</td>
                  </tr>
                `).join('')}
              </table>
            </div>
          ` : ''}

          <div style="margin-top: 28px; padding-top: 16px; border-top: 1px solid #e5e7eb; font-size: 12px; color: #9ca3af; text-align: center;">
            This email was automatically generated by the Enterprise Knowledge Assistant system. Please do not reply directly to this automated email.
          </div>
        </div>
      </div>
    `;

    return htmlBody;
  }

  /**
   * Dispatch email via SMTP
   */
  async sendEmail({ to, subject, type = 'CUSTOM', body, variables, senderName = 'Enterprise Knowledge Assistant' }) {
    const startTime = Date.now();
    const htmlContent = this.generateEmailTemplate({ type, recipient: to, subject, body, variables });

    let messageId = `msg_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;
    const isApproval = (subject && subject.toUpperCase().startsWith('APPROVED')) || type === 'LEAVE_APPROVAL';
    let status = isApproval ? 'APPROVED' : 'SENT';
    let etherealUrl = null;
    let errorMessage = null;

    try {
      if (this.transporter) {
        const fromEmail = config.smtp.fromEmail || config.smtp.user || 'assistant@enterprise.corp';
        const fromName = senderName || config.smtp.fromName || 'Enterprise Knowledge Assistant';
        const info = await this.transporter.sendMail({
          from: `"${fromName}" <${fromEmail}>`,
          to,
          subject,
          html: htmlContent
        });

        messageId = info.messageId || messageId;
        etherealUrl = nodemailer.getTestMessageUrl(info) || null;
      } else {
        // Local simulation fallback
        status = 'SENT (SIMULATED)';
      }
    } catch (err) {
      console.error('[EmailService] Error sending email via SMTP:', err.message);
      status = 'FAILED';
      errorMessage = err.message;
    }

    const logEntry = {
      id: `log_email_${Date.now()}`,
      messageId,
      to,
      subject,
      type,
      senderName,
      status,
      etherealUrl,
      errorMessage,
      latencyMs: Date.now() - startTime,
      sentAt: new Date().toISOString(),
      previewSnippet: body ? body.substring(0, 100) + '...' : subject
    };

    this.emailLogs.unshift(logEntry);
    return logEntry;
  }

  /**
   * Get email logs
   */
  getLogs() {
    return this.emailLogs;
  }
}

export const emailService = new EmailService();
